//! FFmpeg's seven libraries. Enabled components and source lists are resolved at build-graph
//! time from configure's declarations and the Makefiles (build/ffmpeg/resolve.zig).
const std = @import("std");
const Ctx = @import("Ctx.zig");
const Nasm = @import("Nasm.zig");
const Meta = @import("Meta.zig");
const config = @import("ffmpeg/config.zig");
const resolve = @import("ffmpeg/resolve.zig");
const programs = @import("ffmpeg/programs.zig");

/// The metadata of the FFmpeg release `v` pins.
pub fn meta(comptime v: resolve.Version) Meta {
    return .{
        .name = "ffmpeg",
        .zon = v.pin(),
        .version = v.data().version,
        .licenses = &.{ "COPYING.GPLv2", "COPYING.GPLv3", "COPYING.LGPLv2.1", "COPYING.LGPLv3", "LICENSE.md" },
    };
}

/// The pins of the FFmpeg release `v`, as a bundle's MANIFEST records them.
pub fn sources(v: resolve.Version) []const Meta.Source {
    return switch (v) {
        inline else => |tag| comptime Meta.sources(meta(tag)),
    };
}

/// Static libraries in link order: each depends only on those after it.
pub const link_order = [_][]const u8{ "avdevice", "avfilter", "avformat", "avcodec", "swresample", "swscale", "avutil" };

pub const Probe = resolve.Probe;

pub const Version = resolve.Version;

pub const Options = struct {
    /// The FFmpeg release to build.
    version: Version,
    /// configure names of the external libraries in `deps` (`libvpx`, `vaapi`).
    libraries: []const []const u8,
    /// Probe names of every registry library, built or not.
    probes: []const Probe = &.{},
    /// `--enable-version3`.
    version3: bool = false,
    /// Also build ffmpeg and ffprobe against the archives.
    programs: bool = false,
};

pub fn build(c: Ctx, nasm: Nasm, deps: []const Meta.Built, o: Options) []const *std.Build.Step.Compile {
    const b = c.b;
    const t = c.target.result;
    const src = c.lazyUpstream(o.version.pin()) orelse return &.{};

    const libraries = std.mem.concat(b.allocator, []const u8, &.{ o.libraries, config.systemLibraries(t) }) catch @panic("OOM");
    var state: resolve.State = .init(b.allocator, o.version);
    config.apply(c, &state);
    state.configure(.{ .gpl = c.gpl, .version3 = o.version3, .libraries = libraries, .probes = o.probes });
    state.resolve();

    const headers = config.add(c, &state, .{ .gpl = c.gpl, .version3 = o.version3, .libraries = libraries });
    const wf = b.addWriteFiles();
    var generated: std.ArrayList([2][]const u8) = .empty;
    generated.append(b.allocator, .{ "config_components.h", state.componentsFile(false) }) catch @panic("OOM");
    if (state.enabled("x86asm")) {
        generated.append(b.allocator, .{ "config_components.asm", state.componentsFile(true) }) catch @panic("OOM");
    }
    for (state.data.component_files) |f| {
        generated.append(b.allocator, .{ f.path, state.listFile(f) }) catch @panic("OOM");
    }
    generated.append(b.allocator, .{
        "libavutil/ffversion.h",
        b.fmt("/* Automatically generated by version.sh, do not manually edit! */\n#ifndef AVUTIL_FFVERSION_H\n" ++
            "#define AVUTIL_FFVERSION_H\n#define FFMPEG_VERSION \"{s}\"\n#endif /* AVUTIL_FFVERSION_H */\n", .{state.data.version}),
    }) catch @panic("OOM");
    for (generated.items) |g| _ = wf.add(g[0], g[1]);
    const gen = wf.getDirectory();

    const embed = b.addExecutable(.{
        .name = "embed",
        .root_module = b.createModule(.{
            .root_source_file = b.path("build/ffmpeg/embed.zig"),
            .target = b.graph.host,
            .optimize = .ReleaseFast,
        }),
    });

    var dep_includes: std.ArrayList(std.Build.LazyPath) = .empty;
    var dep_archives: std.ArrayList(*std.Build.Step.Compile) = .empty;
    var base_flags: std.ArrayList([]const u8) = .empty;
    base_flags.appendSlice(b.allocator, &common_flags) catch @panic("OOM");
    base_flags.appendSlice(b.allocator, osFlags(t)) catch @panic("OOM");
    for (deps) |dep| {
        for ([_][]const []const u8{ dep.meta.ffmpeg_defines, if (t.os.tag == .windows) dep.meta.ffmpeg_windows_defines else &.{} }) |defines| {
            for (defines) |d| base_flags.append(b.allocator, b.fmt("-D{s}", .{d})) catch @panic("OOM");
        }
        const tree = dep.output.include;
        dep_includes.append(b.allocator, tree) catch @panic("OOM");
        for (dep.output.archives) |archive| dep_archives.append(b.allocator, archive.lib) catch @panic("OOM");
        for (dep.meta.ffmpeg_include_subdirs) |sub| {
            dep_includes.append(b.allocator, tree.path(b, sub)) catch @panic("OOM");
        }
    }

    var manifest: std.ArrayList([]const u8) = .empty;
    const config_step = b.step("ffmpeg-config", "Install only FFmpeg's resolved configuration to <prefix>/share/ffmpeg-hermetic/config");
    for ([_]struct { *std.Build.Step.ConfigHeader, []const u8 }{
        .{ headers.config_h, "config.h" },
        .{ headers.config_asm, "config.asm" },
        .{ headers.avconfig_h, "libavutil/avconfig.h" },
    }) |entry| {
        if (entry[0] == headers.config_asm and !state.enabled("x86asm")) continue;
        installConfig(b, config_step, entry[0].getOutputFile(), entry[1]);
    }
    for (generated.items) |g| installConfig(b, config_step, gen.path(b, g[0]), g[0]);

    const dirs = archDirs(&state, t);
    const global_includes = config.compatIncludes(t, &state);
    var host_exes: std.StringHashMapUnmanaged(*std.Build.Step.Compile) = .empty;
    var out: std.ArrayList(*std.Build.Step.Compile) = .empty;
    for (state.data.libraries) |lib| {
        if (!state.enabled(lib.name)) continue;
        const srcs = state.sources(lib, dirs);
        var flags: std.ArrayList([]const u8) = .empty;
        flags.appendSlice(b.allocator, base_flags.items) catch @panic("OOM");
        flags.append(b.allocator, b.fmt("-DBUILDING_{s}", .{lib.name})) catch @panic("OOM");
        if (t.cpu.arch.isX86()) flags.append(b.allocator, "-mstack-alignment=16") catch @panic("OOM");

        const mod = c.module(.{});
        for (srcs.c.items, 0..) |group, i| {
            const includes = std.mem.concat(b.allocator, []const u8, &.{ global_includes, group.includes }) catch @panic("OOM");
            const setup: Setup = .{ .headers = headers, .gen = gen, .src = src, .includes = includes, .deps = dep_includes.items };
            if (group.includes.len == 0) {
                Setup.apply(mod, setup);
                mod.addCSourceFiles(.{ .root = src.path(""), .files = group.files, .flags = flags.items });
            } else {
                c.addSources(mod, b.fmt("{s}_group{d}", .{ lib.name, i }), .{
                    .setup = .{
                        .config_headers = &.{ headers.config_h, headers.avconfig_h },
                        .includes = std.mem.concat(b.allocator, std.Build.LazyPath, &.{
                            &.{ gen, src.path("") },
                            c.includeDirs(src.path(""), includes),
                            dep_includes.items,
                        }) catch @panic("OOM"),
                    },
                    .groups = &.{.{ .root = src.path(""), .files = group.files, .flags = flags.items }},
                });
            }
            for (group.files) |f| manifest.append(b.allocator, b.fmt("{s} c {s} {s}", .{ lib.name, joinOrDash(b, includes), f })) catch @panic("OOM");
        }

        if (srcs.nasm.items.len > 0) {
            for (lib.preprocessed) |p| {
                if (!inList(dirs, p[2])) continue;
                const cpp = b.addSystemCommand(&.{ b.graph.zig_exe, "cc", "-E", "-P", "-x", "c", "-o" });
                const out_file = cpp.addOutputFileArg(std.fs.path.basename(p[0]));
                cpp.addFileArg(src.path(p[1]));
                _ = wf.addCopyFile(out_file, p[0]);
            }
            nasm.addFiles(c, mod, .{
                .root = src.path(""),
                .files = srcs.nasm.items,
                .include_dirs = &.{ gen, src.path(""), src.path(b.fmt("lib{s}/x86", .{lib.name})) },
                .preincludes = &.{headers.config_asm.getOutputFile()},
                // configure's X86ASMFLAGS: x86inc prefixes symbols with `_` when PREFIX is defined.
                .flags = if (t.os.tag.isDarwin()) &.{"-DPREFIX"} else &.{},
            });
        }
        var as_flags: std.ArrayList([]const u8) = .empty;
        for (flags.items) |f| if (std.mem.startsWith(u8, f, "-D")) as_flags.append(b.allocator, f) catch @panic("OOM");
        if (srcs.gas.items.len > 0) {
            mod.addCSourceFiles(.{ .root = src.path(""), .files = srcs.gas.items, .flags = as_flags.items });
        }
        for (srcs.hostgen.items) |path| {
            const gen_file = addHostGen(b, src, &host_exes, lib, path);
            mod.addCSourceFile(.{ .file = gen_file, .flags = if (std.mem.endsWith(u8, path, ".S")) as_flags.items else flags.items });
        }

        const compress = state.enabled("shader_compression");
        for (srcs.cuda.items) |cu| addCuda(c, mod, src, embed, cu, compress);
        for (srcs.opencl.items) |cl| {
            const run = b.addRunArtifact(embed);
            run.addFileArg2(src.path(cl), .{});
            const base = std.fs.path.basename(cl);
            const c_file = run.addOutputFileArg2(b.fmt("{s}.c", .{std.fs.path.stem(cl)}), .{});
            const name = b.allocator.dupe(u8, base) catch @panic("OOM");
            if (std.mem.indexOfScalar(u8, name, '.')) |dot| name[dot] = '_';
            run.addArgs(&.{ name, "source" });
            mod.addCSourceFile(.{ .file = c_file });
        }

        for ([_]struct { []const u8, []const []const u8 }{ .{ "nasm", srcs.nasm.items }, .{ "gas", srcs.gas.items }, .{ "cuda", srcs.cuda.items }, .{ "opencl", srcs.opencl.items } }) |k| {
            for (k[1]) |f| manifest.append(b.allocator, b.fmt("{s} {s} - {s}", .{ lib.name, k[0], f })) catch @panic("OOM");
        }
        for (srcs.hostgen.items) |f| {
            manifest.append(b.allocator, b.fmt("{s} {s} - {s}", .{ lib.name, if (std.mem.endsWith(u8, f, ".S")) "gas" else "c", f })) catch @panic("OOM");
        }
        for ([_][]const []const u8{ lib.headers, lib.built_headers }) |hs| for (hs) |h| {
            manifest.append(b.allocator, b.fmt("{s} header - {s}", .{ lib.name, h })) catch @panic("OOM");
        };

        const artifact = c.staticLibrary(lib.name, mod);
        for (srcs.unsupported.items) |f| {
            artifact.step.dependOn(&b.addFail(b.fmt("FFmpeg's lib{s} needs {s}, which this build cannot compile", .{ lib.name, f })).step);
        }
        for (lib.headers) |h| {
            artifact.installHeader(src.path(b.fmt("lib{s}/{s}", .{ lib.name, h })), b.fmt("lib{s}/{s}", .{ lib.name, h }));
        }
        if (std.mem.eql(u8, lib.name, "avutil")) {
            artifact.installConfigHeader(headers.avconfig_h);
            artifact.installHeader(gen.path(b, "libavutil/ffversion.h"), "libavutil/ffversion.h");
        }
        out.append(b.allocator, artifact) catch @panic("OOM");
    }

    var system_libs: std.ArrayList([]const u8) = .empty;
    system_libs.appendSlice(b.allocator, config.systemLinkLibraries(t)) catch @panic("OOM");
    for (deps) |dep| for (dep.meta.system_libs.forTarget(c)) |name| {
        if (!inList(system_libs.items, name)) system_libs.append(b.allocator, name) catch @panic("OOM");
    };
    if (o.programs) programs.add(c, .{
        .data = state.data,
        .headers = headers,
        .gen = gen,
        .src = src,
        .includes = std.mem.concat(b.allocator, std.Build.LazyPath, &.{ c.includeDirs(src.path(""), global_includes), dep_includes.items }) catch @panic("OOM"),
        .flags = base_flags.items,
        .embed = embed,
        .compress = state.enabled("resource_compression"),
        .libs = out.items,
        .deps = dep_archives.items,
        .system_libs = system_libs.items,
    });

    std.mem.sort([]const u8, manifest.items, {}, struct {
        fn lt(_: void, x: []const u8, y: []const u8) bool {
            return std.mem.lessThan(u8, x, y);
        }
    }.lt);
    const listing = std.mem.join(b.allocator, "\n", manifest.items) catch @panic("OOM");
    const sources_txt = b.addWriteFiles().add("sources.txt", b.fmt("{s}\n", .{listing}));
    installConfig(b, config_step, sources_txt, "sources.txt");
    return out.items;
}

/// The output of `lib`'s host program for `path`: what it prints when run with the path's flag.
/// `exes` holds each program built so far, so one program with several outputs compiles once.
fn addHostGen(b: *std.Build, src: *std.Build.Dependency, exes: *std.StringHashMapUnmanaged(*std.Build.Step.Compile), lib: resolve.Library, path: []const u8) std.Build.LazyPath {
    for (lib.host_programs) |prog| for (prog.outputs) |out| {
        if (!std.mem.eql(u8, out[1], path)) continue;
        const slot = exes.getOrPut(b.allocator, prog.path) catch @panic("OOM");
        if (!slot.found_existing) slot.value_ptr.* = hostProgram(b, src, prog);
        const run = b.addRunArtifact(slot.value_ptr.*);
        run.addArg(out[0]);
        return run.captureStdOut(.{ .basename = std.fs.path.basename(path) });
    };
    std.debug.panic("no host program of lib{s} writes {s}", .{ lib.name, path });
}

fn hostProgram(b: *std.Build, src: *std.Build.Dependency, prog: resolve.HostProgram) *std.Build.Step.Compile {
    const exe = b.addExecutable(.{
        .name = std.fs.path.basename(prog.path),
        .root_module = b.createModule(.{ .target = b.graph.host, .optimize = .ReleaseFast, .link_libc = true }),
    });
    // configure's HOSTCFLAGS and HOSTCPPFLAGS.
    exe.root_module.addCSourceFile(.{
        .file = src.path(b.fmt("{s}.c", .{prog.path})),
        .flags = &.{ "-std=c17", "-D_ISOC11_SOURCE", "-D_POSIX_C_SOURCE=200112", "-D_XOPEN_SOURCE=600" },
    });
    exe.root_module.addIncludePath(src.path(""));
    return exe;
}

fn installConfig(b: *std.Build, config_step: *std.Build.Step, file: std.Build.LazyPath, name: []const u8) void {
    const install = b.addInstallFile(file, b.fmt("share/ffmpeg-hermetic/config/{s}", .{name}));
    b.getInstallStep().dependOn(&install.step);
    config_step.dependOn(&install.step);
}

/// The library subdirectories whose Makefiles FFmpeg includes: `$(ARCH)` and `$(INTRINSICS)`.
fn archDirs(state: *const resolve.State, t: std.Target) []const []const u8 {
    const arch: []const u8 = switch (t.cpu.arch) {
        .x86, .x86_64 => "x86",
        .aarch64, .aarch64_be => "aarch64",
        .arm, .armeb, .thumb, .thumbeb => "arm",
        .powerpc, .powerpcle, .powerpc64, .powerpc64le => "ppc",
        .mips, .mipsel, .mips64, .mips64el => "mips",
        .riscv32, .riscv64 => "riscv",
        .loongarch32, .loongarch64 => "loongarch",
        .wasm32, .wasm64 => "wasm",
        else => std.debug.panic("no FFmpeg arch directory for {t}", .{t.cpu.arch}),
    };
    var intrinsics: []const u8 = "none";
    for (state.data.lists.intrinsics_list) |name| {
        if (state.enabled(name)) intrinsics = name["intrinsics_".len..];
    }
    return state.gpa.dupe([]const u8, &.{ arch, intrinsics }) catch @panic("OOM");
}

/// Include paths and config headers every FFmpeg C module compiles with.
const Setup = struct {
    headers: config.Headers,
    gen: std.Build.LazyPath,
    src: *std.Build.Dependency,
    /// Extra include dirs the source's Makefile adds, relative to the FFmpeg tree.
    includes: []const []const u8,
    deps: []const std.Build.LazyPath,

    fn apply(m: *std.Build.Module, s: Setup) void {
        m.addConfigHeader(s.headers.config_h);
        m.addConfigHeader(s.headers.avconfig_h);
        m.addIncludePath(s.gen);
        m.addIncludePath(s.src.path(""));
        for (s.includes) |dir| m.addIncludePath(s.src.path(dir));
        for (s.deps) |dir| m.addIncludePath(dir);
    }
};

fn inList(list: []const []const u8, name: []const u8) bool {
    for (list) |item| if (std.mem.eql(u8, item, name)) return true;
    return false;
}

fn joinOrDash(b: *std.Build, items: []const []const u8) []const u8 {
    if (items.len == 0) return "-";
    return std.mem.join(b.allocator, ",", items) catch @panic("OOM");
}

/// `.cu` -> PTX with zig's own clang, then gzip (with shader compression) and embed as C, as
/// FFmpeg's make rules do.
fn addCuda(c: Ctx, mod: *std.Build.Module, src: *std.Build.Dependency, embed: *std.Build.Step.Compile, cu: []const u8, compress: bool) void {
    const b = c.b;
    const stem = std.fs.path.stem(cu);
    const ptx = b.addSystemCommand(&.{ b.graph.zig_exe, "clang", "-x", "cuda" });
    ptx.addArgs(&.{
        "--cuda-gpu-arch=sm_30", "-O2",        "-std=c++11",         "-m64",                 "-S",
        "-nocudalib",            "-nocudainc", "--cuda-device-only", "-Wno-c++11-narrowing",
    });
    // clang picks the PTX ISA version from any CUDA toolkit it finds; a path holding none keeps 4.2.
    ptx.addDirectoryArg2(src.path("compat/cuda"), .{ .prefix = "--cuda-path=" });
    ptx.addArg("-include");
    ptx.addFileArg2(src.path("compat/cuda/cuda_runtime.h"), .{});
    ptx.addDirectoryArg2(src.path(""), .{ .prefix = "-I" });
    ptx.addArg("-o");
    const ptx_file = ptx.addOutputFileArg2(b.fmt("{s}.ptx", .{stem}), .{});
    ptx.addFileArg2(src.path(cu), .{});

    const run = b.addRunArtifact(embed);
    run.addFileArg2(ptx_file, .{});
    const c_file = run.addOutputFileArg2(b.fmt("{s}.ptx.c", .{stem}), .{});
    run.addArg(b.fmt("{s}_ptx", .{stem}));
    if (!compress) run.addArg("raw");
    mod.addCSourceFile(.{ .file = c_file });
}

/// The flags configure adds for the target's OS and libc.
fn osFlags(t: std.Target) []const []const u8 {
    const posix = [_][]const u8{ "-D_POSIX_C_SOURCE=200112", "-D_XOPEN_SOURCE=600" };
    return switch (t.os.tag) {
        .windows => if (t.abi == .msvc)
            &.{ "-DWIN32_LEAN_AND_MEAN", "-D_USE_MATH_DEFINES", "-D_CRT_SECURE_NO_WARNINGS", "-D_CRT_NONSTDC_NO_WARNINGS", "-D_WIN32_WINNT=0x0600" }
        else
            &(.{ "-DWIN32_LEAN_AND_MEAN", "-U__STRICT_ANSI__" } ++ posix),
        .macos, .ios, .tvos, .watchos, .visionos => &.{"-fno-common"},
        else => &posix,
    };
}

const common_flags = [_][]const u8{
    "-D_ISOC11_SOURCE",
    "-D_FILE_OFFSET_BITS=64",
    "-D_LARGEFILE_SOURCE",
    "-DPIC",
    "-DZLIB_CONST",
    "-DHAVE_AV_CONFIG_H",
    "-std=c17",
    "-fomit-frame-pointer",
    "-fno-math-errno",
    "-fno-signed-zeros",
};
