#!/usr/bin/env bash
# Regenerates gen/openssl/<arch> from an OpenSSL source tree.
#
# usage: tools/gen_openssl.sh <openssl-src> [arch...]     (arch: x86_64 aarch64)
#
# Needs perl, make and zig, only here: the checked-in output is what the zig build consumes.
# OpenSSL's own Configure runs out of tree and produces configdata.pm, which lists every source
# of libcrypto.a and libssl.a with its defines; tools/gen_openssl.pl turns that into sources.zig.
# The perlasm assembly, the headers generated from .h.in and the sources generated from .c.in are
# copied next to it. CC is zig so perlasm enables the same ISA extensions zig's assembler accepts.
set -euo pipefail

src=$(realpath "${1:?usage: gen_openssl.sh <openssl-src> [arch...]}")
shift
archs=("$@")
[ ${#archs[@]} -gt 0 ] || archs=(x86_64 aarch64)
root=$(realpath "$(dirname "$0")/..")
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

options=(
  no-shared no-apps no-tests no-docs no-engine no-module no-legacy no-dso no-ssl3 no-comp no-quic
  no-fuzz-afl no-fuzz-libfuzzer enable-ec_nistp_64_gcc_128
  --prefix=/usr --openssldir=/etc/ssl
)

mkdir -p "$root/gen/openssl"
cat > "$root/gen/openssl/group.zig" <<'EOF'
//! Generated by tools/gen_openssl.sh; do not edit.
/// Sources compiled with one set of defines. `c` is relative to the OpenSSL tree; `gen_c` and
/// `asm_files` are relative to the target's gen/openssl directory.
pub const Group = struct {
    defines: []const []const u8,
    includes: []const []const u8,
    c: []const []const u8,
    gen_c: []const []const u8,
    asm_files: []const []const u8,
};
EOF

for arch in "${archs[@]}"; do
  case $arch in
    x86_64) target=linux-x86_64 ;;
    aarch64) target=linux-aarch64 ;;
    *) echo "unknown arch: $arch" >&2; exit 1 ;;
  esac
  build="$work/$arch"
  dest="$root/gen/openssl/$arch"
  mkdir -p "$build"
  (
    cd "$build"
    export CC="zig cc" SOURCE_DATE_EPOCH=0
    perl "$src/Configure" "$target" "${options[@]}"
    make -j4 build_generated
    perl -I. -Mconfigdata "$root/tools/gen_openssl.pl" "$src" sources.zig generated.txt
    # shellcheck disable=SC2046
    make -j4 crypto/buildinf.h $(cat generated.txt)
    rm -rf "$dest"
    mkdir -p "$dest"
    cp sources.zig "$dest/"
    {
      cat generated.txt
      echo crypto/buildinf.h
      find include providers -type f \( -name '*.h' -o -name '*.inc' \)
    } | sort -u | while read -r f; do
      mkdir -p "$dest/$(dirname "$f")"
      cp "$f" "$dest/$f"
    done
    # Generated headers record the source path relative to the build dir; keep that out of the tree.
    rel=$(realpath --relative-to="$build" "$src")
    grep -rlF -- "$rel" "$dest" | xargs -r sed -i "s#$rel#<openssl-src>#g"
  )
done
