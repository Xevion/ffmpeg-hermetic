#!/usr/bin/env python3
"""Extracts FFmpeg's per-library source lists and configure output into gen/ffmpeg/.

usage: ffmpeg_extract.py <configured-build-dir> <out-dir>

Reads `make -n V=1` in a tree configured by tools/ffmpeg_configure.sh. Writes sources.zig (the
C, nasm and CUDA sources each library compiles), the component headers and lists configure
generates, and oracle/ copies of config.h and config.asm that the zig build's computed values
are checked against.
"""
import os
import re
import shlex
import shutil
import subprocess
import sys

LIBS = ["libavutil", "libswresample", "libswscale", "libavcodec", "libavformat", "libavfilter", "libavdevice"]

GENERATED = [
    "config_components.h",
    "config_components.asm",
    "libavutil/ffversion.h",
    "libavcodec/bsf_list.c",
    "libavcodec/codec_list.c",
    "libavcodec/parser_list.c",
    "libavdevice/indev_list.c",
    "libavdevice/outdev_list.c",
    "libavfilter/filter_list.c",
    "libavformat/demuxer_list.c",
    "libavformat/muxer_list.c",
    "libavformat/protocol_list.c",
]
ORACLE = ["config.h", "config.asm", "libavutil/avconfig.h"]


def scrub_configuration(text):
    """Replaces the machine-local tool and prefix paths in FFMPEG_CONFIGURATION with placeholders."""
    def scrub(m):
        line = re.sub(r"/[^ ']*/(tools/(?:cc|c\+\+|ar|ranlib))", r"<build>/\1", m.group(0))
        return re.sub(r"(-[IL])/[^ ']*/(include|lib)\b", r"\1<prefix>/\2", line)

    return re.sub(r"^#define FFMPEG_CONFIGURATION .*$", scrub, text, flags=re.M)


def source_of(tokens):
    for t in reversed(tokens):
        if t.startswith("src/"):
            return t[len("src/"):]
    return None


def source_includes(tokens, src_root):
    """Include dirs inside the FFmpeg tree beyond the build and source roots, relative to it."""
    dirs = []
    for t in tokens:
        if t.startswith("-I"):
            d = os.path.realpath(t[2:])
            if d.startswith(src_root + "/"):
                dirs.append(os.path.relpath(d, src_root))
    return tuple(dirs)


def main():
    bld, out = os.path.realpath(sys.argv[1]), sys.argv[2]
    src_root = os.path.realpath(os.path.join(bld, "src"))
    plan = subprocess.run(["make", "-n", "V=1"], cwd=bld, capture_output=True, text=True, check=True).stdout
    sources = {lib: {"c": {}, "nasm": set(), "gas": set(), "cuda": set(), "headers": set()} for lib in LIBS}
    for line in plan.splitlines():
        if " -o " not in line:
            continue
        tokens = shlex.split(line)
        obj = tokens[tokens.index("-o") + 1]
        lib = obj.split("/")[0]
        if lib not in sources:
            continue
        src = source_of(tokens)
        if src is None:
            continue
        if src.endswith(".cu"):
            sources[lib]["cuda"].add(src)
        elif src.endswith(".asm"):
            sources[lib]["nasm"].add(src)
        elif src.endswith(".S"):
            sources[lib]["gas"].add(src)
        elif src.endswith(".c") and "-c" in tokens:
            sources[lib]["c"].setdefault(source_includes(tokens, src_root), set()).add(src)

    os.makedirs(os.path.join(out, "oracle"), exist_ok=True)
    for rel in GENERATED:
        dst = os.path.join(out, rel)
        os.makedirs(os.path.dirname(dst) or out, exist_ok=True)
        shutil.copyfile(os.path.join(bld, rel), dst)
    for rel in ORACLE:
        dst = os.path.join(out, "oracle", rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if rel == "config.h":
            with open(os.path.join(bld, rel), newline="") as f:
                text = f.read()
            with open(dst, "w", newline="") as f:
                f.write(scrub_configuration(text))
        else:
            shutil.copyfile(os.path.join(bld, rel), dst)

    install = subprocess.run(["make", "-n", "install"], cwd=bld, capture_output=True, text=True, check=True).stdout
    for line in install.splitlines():
        for cmd in line.split(";"):
            tokens = shlex.split(cmd)
            if tokens[:3] != ["install", "-m", "644"] or not tokens[-1].endswith(tuple("/include/" + l for l in LIBS)):
                continue
            lib = os.path.basename(tokens[-1])
            for h in tokens[3:-1]:
                if h.endswith(".h"):
                    sources[lib]["headers"].add(os.path.basename(h))

    with open(os.path.join(out, "sources.zig"), "w") as f:
        f.write("//! Generated by tools/ffmpeg_extract.py from a configured FFmpeg tree. Do not edit.\n\n")
        f.write('const Library = @import("../../../build/ffmpeg/Sources.zig").Library;\n\n')
        f.write("pub const libraries = [_]Library{\n")
        for lib in LIBS:
            f.write(f'    .{{\n        .name = "{lib[3:]}",\n')
            f.write("        .c = &.{\n")
            for inc, files in sorted(sources[lib]["c"].items()):
                incs = ", ".join(f'"{i}"' for i in inc)
                f.write(f"            .{{\n                .includes = &.{{{incs}}},\n                .files = &.{{\n")
                for s_ in sorted(files):
                    f.write(f'                    "{s_}",\n')
                f.write("                },\n            },\n")
            f.write("        },\n")
            for kind in ("nasm", "gas", "cuda", "headers"):
                items = sorted(sources[lib][kind])
                if not items:
                    f.write(f"        .{kind} = &.{{}},\n")
                    continue
                f.write(f"        .{kind} = &.{{\n")
                for s in items:
                    f.write(f'            "{s}",\n')
                f.write("        },\n")
            f.write("    },\n")
        f.write("};\n")
    total = {k: sum(len(v[k]) for v in sources.values()) for k in ("nasm", "gas", "cuda", "headers")}
    total["c"] = sum(len(f) for v in sources.values() for f in v["c"].values())
    print(f"wrote {out}: {total}")


if __name__ == "__main__":
    main()
