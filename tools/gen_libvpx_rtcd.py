#!/usr/bin/env python3
"""Regenerate the checked-in libvpx run-time CPU detection headers.

usage: gen_libvpx_rtcd.py <libvpx-source-root> [out-dir]

Runs libvpx's own configure (parity flags of the ffoxide shell build) out of tree for each
supported target, then rtcd.pl exactly as libs.mk's rtcd_h_template does, and writes
vp8_rtcd.h, vp9_rtcd.h, vpx_dsp_rtcd.h and vpx_scale_rtcd.h under <out-dir>/<arch>/.
Needs bash, perl and a C compiler; users of the zig build do not. The arm64 variant is
configured with zig cc as the cross compiler, so it also needs zig on PATH.
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.realpath(__file__))

# gen subdirectory -> (configure target, rtcd.pl --arch, extra configure flags)
TARGETS = {
    "x86_64": ("x86_64-linux-gcc", "x86_64", ["--as=nasm"]),
    "generic": ("generic-gnu", "generic", ["--as=nasm"]),
    "arm64": ("arm64-linux-gcc", "arm64", []),
}

# configure probes -march flags that zig cc does not take, so map them to -mcpu feature lists.
ZIG_CC_WRAPPER = """#!/bin/bash
args=()
for a in "$@"; do
  case "$a" in
    -march=armv8-a) ;;
    -march=armv8.2-a+*) args+=("-mcpu=generic+v8_2a+${a#-march=armv8.2-a+}") ;;
    -march=armv9-a+*) args+=("-mcpu=generic+v9a+${a#-march=armv9-a+}") ;;
    *) args+=("$a") ;;
  esac
done
exec zig cc -target aarch64-linux-gnu.2.17 "${args[@]}"
"""

COMMON = [
    "--enable-runtime-cpu-detect", "--enable-pic", "--disable-shared", "--enable-static", "--disable-examples", "--disable-tools", "--disable-docs",
    "--disable-unit-tests", "--disable-install-bins", "--enable-vp8", "--enable-vp9",
    "--enable-vp9-highbitdepth",
]

HEADERS = [
    ("vp8_rtcd", "vp8/common/rtcd_defs.pl"),
    ("vp9_rtcd", "vp9/common/vp9_rtcd_defs.pl"),
    ("vpx_dsp_rtcd", "vpx_dsp/vpx_dsp_rtcd_defs.pl"),
    ("vpx_scale_rtcd", "vpx_scale/vpx_scale_rtcd.pl"),
]

BANNER = "// Generated by tools/gen_libvpx_rtcd.py from libvpx rtcd.pl; do not edit."


def zig_cross_env(tools):
    """A CROSS prefix whose gcc, g++, ar, as and ld are zig cc based, for the arm64 target."""
    for name in ("gcc", "g++", "as", "ld"):
        path = os.path.join(tools, f"aarch64-linux-gnu-{name}")
        with open(path, "w") as f:
            f.write(ZIG_CC_WRAPPER)
        os.chmod(path, 0o755)
    path = os.path.join(tools, "aarch64-linux-gnu-ar")
    with open(path, "w") as f:
        f.write('#!/bin/sh\nexec zig ar "$@"\n')
    os.chmod(path, 0o755)
    return {**os.environ, "CROSS": "aarch64-linux-gnu-", "PATH": tools + os.pathsep + os.environ["PATH"]}


def main():
    src = os.path.realpath(sys.argv[1])
    out = os.path.realpath(sys.argv[2]) if len(sys.argv) > 2 else os.path.join(HERE, "..", "gen", "libvpx")
    out = os.path.realpath(out)
    for sub, (target, arch, extra) in TARGETS.items():
        with tempfile.TemporaryDirectory() as bld, tempfile.TemporaryDirectory() as tools:
            flags = [f"--target={target}"] + COMMON + extra
            env = zig_cross_env(tools) if arch == "arm64" else None
            with open(os.path.join(bld, "configure.log"), "w") as log:
                subprocess.run([os.path.join(src, "configure")] + flags, cwd=bld, check=True, stdout=log, env=env)
            if arch == "arm64":
                with open(os.path.join(bld, "vpx_config.h")) as f:
                    cfg = f.read()
                for feat in ("NEON", "NEON_DOTPROD", "NEON_I8MM", "SVE", "SVE2"):
                    assert f"#define HAVE_{feat} 1\n" in cfg, f"configure disabled {feat}"
            dest = os.path.join(out, sub)
            os.makedirs(dest, exist_ok=True)
            for sym, defs in HEADERS:
                text = subprocess.run(
                    [os.path.join(src, "build/make/rtcd.pl"), f"--arch={arch}", f"--sym={sym}",
                     f"--config=libs-{target}.mk", os.path.join(src, defs)],
                    cwd=bld, check=True, capture_output=True, text=True,
                ).stdout
                text, n = re.subn(r"^// This file is generated\. Do not edit\.$", BANNER, text, flags=re.M)
                assert n == 1, f"{sym}: banner line not found"
                with open(os.path.join(dest, sym + ".h"), "w") as f:
                    f.write(text)
            print(f"{sub}: {target}")


if __name__ == "__main__":
    main()
