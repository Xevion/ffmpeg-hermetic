#!/usr/bin/env bash
# Regenerates gen/libaom/<arch>/*_rtcd.h from a libaom source tree.
#
# usage: tools/gen_libaom_rtcd.sh <libaom-src> [arch...]     (arch: x86_64 x86 arm64 generic)
#
# Needs perl, only here: the checked-in output is what the zig build consumes. Each header is
# produced the way libaom's cmake does (cmake/aom_configure.cmake):
#   perl cmake/rtcd.pl --arch=<arch> --sym=<sym> --config=<aom_config.h> <defs.pl>
# rtcd.pl reads only the AOM_ARCH_/CONFIG_/HAVE_ defines of the config file, so a minimal one
# carrying the values cmake would compute (all SIMD flavors on, runtime CPU detection, encoder and
# decoder, high bitdepth) gives byte-identical output to a full configure.
set -euo pipefail

src=$(realpath "${1:?usage: gen_libaom_rtcd.sh <libaom-src> [arch...]}")
shift
archs=("$@")
[ ${#archs[@]} -gt 0 ] || archs=(x86_64 x86 arm64 generic)
out_root=$(realpath "$(dirname "$0")/..")/gen/libaom
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

common=(
  CONFIG_AV1_DECODER CONFIG_AV1_ENCODER CONFIG_AV1_HIGHBITDEPTH CONFIG_RUNTIME_CPU_DETECT
)

for arch in "${archs[@]}"; do
  case $arch in
    x86_64) on=(AOM_ARCH_X86_64 HAVE_MMX HAVE_SSE HAVE_SSE2 HAVE_SSE3 HAVE_SSSE3 HAVE_SSE4_1 HAVE_SSE4_2 HAVE_AVX HAVE_AVX2) ;;
    x86) on=(AOM_ARCH_X86 HAVE_MMX HAVE_SSE HAVE_SSE2 HAVE_SSE3 HAVE_SSSE3 HAVE_SSE4_1 HAVE_SSE4_2 HAVE_AVX HAVE_AVX2) ;;
    arm64) on=(AOM_ARCH_ARM AOM_ARCH_AARCH64 HAVE_NEON HAVE_ARM_CRC32 HAVE_NEON_DOTPROD HAVE_NEON_I8MM HAVE_SVE HAVE_SVE2) ;;
    generic) on=() ;;
    *) echo "unknown arch: $arch" >&2; exit 1 ;;
  esac
  cfg="$work/$arch.h"
  for d in "${common[@]}" "${on[@]}"; do echo "#define $d 1"; done > "$cfg"
  dest="$out_root/$arch"
  mkdir -p "$dest"
  gen() {
    local sym=$1 defs=$2
    {
      echo "/* Generated by tools/gen_libaom_rtcd.sh. */"
      perl "$src/cmake/rtcd.pl" --arch="$arch" --sym="$sym" --config="$cfg" "$src/$defs"
    } > "$dest/$sym.h"
  }
  gen aom_dsp_rtcd aom_dsp/aom_dsp_rtcd_defs.pl
  gen aom_scale_rtcd aom_scale/aom_scale_rtcd.pl
  gen av1_rtcd av1/common/av1_rtcd_defs.pl
done
